#!/usr/bin/env python3
"""
Emit Model PaymentGroup individuals from data/payments.sqlite: one group per
fee-relevant tuple (merchant, card scheme, year, month, credit, ACI, intracountry)
with the number of payments and their total EUR volume.
Output: dabstep-groups-<n>.bsl chunks. Matching and fees are derived by the model.
"""
import sqlite3
from pathlib import Path

ROOT = Path(__file__).resolve().parent
CHUNK = 500


def group_label(merchant, scheme, year, month, is_credit, aci, intra) -> str:
    return f"PG-{merchant}-{scheme}-{year}-{month:02d}-{'credit' if is_credit else 'debit'}-{aci}-{'intra' if intra else 'cross'}"


def main() -> None:
    conn = sqlite3.connect(f"file:{ROOT / 'data' / 'payments.sqlite'}?mode=ro", uri=True)
    rows = conn.execute(
        """
        SELECT merchant, card_scheme, year, tx_month, is_credit, aci, is_intracountry,
               COUNT(*) AS n, SUM(eur_amount) AS vol
        FROM payments
        GROUP BY 1, 2, 3, 4, 5, 6, 7
        ORDER BY 1, 3, 4, 2, 5, 6, 7
        """
    ).fetchall()
    for old in ROOT.glob("dabstep-groups-*.bsl"):
        old.unlink()
    for ci in range(0, len(rows), CHUNK):
        part = rows[ci : ci + CHUNK]
        n = ci // CHUNK + 1
        lines = [
            f"# DABstep payment groups, part {n} ({len(part)} of {len(rows)}).",
            "# Auto-generated by build_payment_groups.py from data/payments.sqlite.",
            "",
        ]
        for m, sc, y, mo, cr, aci, intra, cnt, vol in part:
            lines += [
                f"PaymentGroup: Individual: {group_label(m, sc, y, mo, cr, aci, intra)}",
                ": Model: Model PaymentGroup",
                f": merchant: {m}",
                f": cardScheme: {sc}",
                f": txYear: {y}",
                f": txMonth: {mo}",
                f": isCredit: {int(cr)}",
                f": aci: ACI-{aci}",
                f": isIntracountry: {int(intra)}",
                f": txCount: {cnt}",
                f": totalVolume: {round(vol, 2)}",
                "",
            ]
        (ROOT / f"dabstep-groups-{n}.bsl").write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(rows)} groups -> {(len(rows) + CHUNK - 1) // CHUNK} files")


if __name__ == "__main__":
    main()
